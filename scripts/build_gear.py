#!/usr/bin/env python3
"""Rebuild data/gear.js from a gear CSV.

Usage: python3 scripts/build_gear.py path/to/gear.csv

Columns: band, member, role, category, brand, model, relationship, source_url, confidence, notes
relationship: endorsement | signature_model | seen_using | fan_submitted
Rows with category "none" (nothing found) are skipped.
To publish an approved fan submission, add a row with relationship "fan_submitted" and the
submission's link as source_url, then rerun this script.
"""
import csv, json, re, sys, unicodedata, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "gear.js"
RELATIONSHIPS = {"endorsement", "signature_model", "seen_using", "fan_submitted"}

def slugify(s):
    s = unicodedata.normalize("NFD", s).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")

def main(path):
    gear = {}
    with open(path, newline="", encoding="utf-8-sig") as f:
        for row in csv.DictReader(f):
            cat = (row.get("category") or "").strip().lower()
            band = (row.get("band") or "").strip()
            if not band or not cat or cat == "none" or not (row.get("brand") or row.get("model")):
                continue
            rel = (row.get("relationship") or "").strip().lower()
            gear.setdefault(slugify(band), []).append({
                "member": (row.get("member") or "").strip(),
                "role": re.sub(r"[()]", "", (row.get("role") or "")).strip(),
                "category": cat.replace("_", " "),
                "brand": (row.get("brand") or "").strip(),
                "model": (row.get("model") or "").strip(),
                "relationship": rel if rel in RELATIONSHIPS else "seen_using",
                "source": (row.get("source_url") or "").strip(),
                "confidence": (row.get("confidence") or "").strip().lower(),
            })
    OUT.write_text("/* Generated by scripts/build_gear.py from the gear CSV. Keyed by band slug. */\n"
                   "window.RER_GEAR = " + json.dumps(gear, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
    print("wrote %d items for %d bands to %s" % (sum(map(len, gear.values())), len(gear), OUT))

if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
